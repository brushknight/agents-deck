// Generates src/hats.c from the web deck's HAT_ART (backend/internal/web/static/app.js),
// so the panel's hats are the deck's. Run after the hats change:
//   node tools/gen_hats.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const js = readFileSync(join(here, '../../../../backend/internal/web/static/app.js'), 'utf8');
const start = js.indexOf('const HAT_ART = {');
const end = js.indexOf('\n};', start);
const HAT_ART = new Function(js.slice(start, end + 3) + '\nreturn HAT_ART;')();

let out = `// Generated by tools/gen_hats.mjs from the web deck's HAT_ART. Do not edit.
#include "critter.h"

`;
const names = [];
let n = 0;
const frame = (f) => {
  const id = `f${n++}`;
  out += `static const char *const ${id}_rows[] = {${f.rows.map((r) => JSON.stringify(r)).join(', ')}};\n`;
  if (f.extras.length) out += `static const hat_extra_t ${id}_extras[] = {${f.extras.map(([x, y, k]) => `{${x}, ${y}, '${k}'}`).join(', ')}};\n`;
  return `{${f.x}, ${f.top}, ${f.rows.length}, ${id}_rows, ${f.extras.length}, ${f.extras.length ? `${id}_extras` : 'NULL'}}`;
};
const hats = [];
for (const [name, art] of Object.entries(HAT_ART)) {
  const cs = frame(art.critterStill), os = frame(art.onigiriStill);
  const cf = art.critter.map(frame), of = art.onigiri.map(frame);
  const id = `hat${hats.length}`;
  out += `static const hat_frame_t ${id}_critter[] = {${cf.join(', ')}};\n`;
  out += `static const hat_frame_t ${id}_onigiri[] = {${of.join(', ')}};\n\n`;
  hats.push(`\t{${JSON.stringify(name)}, ${art.ms}, ${cs}, ${cf.length}, ${id}_critter, ${os}, ${of.length}, ${id}_onigiri},`);
  names.push(name);
}
out += `const hat_art_t hat_art[] = {\n${hats.join('\n')}\n};\nconst int hat_art_count = ${hats.length};\n`;
writeFileSync(join(here, '../src/hats.c'), out);
console.log(`src/hats.c: ${names.length} hats (${names.join(', ')})`);
