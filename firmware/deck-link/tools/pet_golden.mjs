// Prints the expected looks for test/host/test_pet.c from the web deck's
// pets.js, so the kit's pets (src/deck_pet.c) stay the same pixels:
//
//   node tools/pet_golden.mjs [folder with pets.js] > test/host/pet_golden.h
//
// Each line is one pet, holding still: its inputs and an FNV-1a hash of its
// cells ("x,y,key;" in rows, top to bottom, left to right).
import { pathToFileURL } from 'node:url';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = resolve(process.argv[2] || resolve(here, '../../../backend/internal/web/static'));
const { petLook } = await import(pathToFileURL(`${dir}/pets.js`).href);
const STAGES = ['egg', 'baby', 'kid', 'grown', 'strong', 'mighty', 'legend'];
const MOODS = ['fed', 'hungry', 'weak', 'asleep'];
const SHAPES = ['hard hat', 'cap', 'beanie', 'helmet', 'wizard', 'beret', 'chef', 'crown', 'headphones',
  'propeller', 'top hat', 'cowboy', 'bandana', 'devil horns'];

const at = (k) => k.split(',').map(Number);

function fnv(h, str) {
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

function hashOf(cells) {
  const list = [...cells].map(([k, ch]) => [...at(k), ch]).sort((a, b) => a[1] - b[1] || a[0] - b[0]);
  return fnv(0x811c9dc5, list.map(([x, y, ch]) => `${x},${y},${ch};`).join(''));
}

// The pets: stage, mood, cracked, ready, the pet's own hat (1 + shape, 0 none),
// with their eyes open and shut (idle).
const PETS = [];
for (let stage = 0; stage < STAGES.length; stage++)
  for (let mood = 0; mood < MOODS.length; mood++)
    for (const cracked of stage === 0 ? [0, 1] : [0]) PETS.push([stage, mood, cracked, 0, stage >= 2 ? 1 + ((stage * 4 + mood) % SHAPES.length) : 0]);
for (let hat = 0; hat <= SHAPES.length; hat++) PETS.push([2, 0, 0, 0, hat], [3, 0, 0, 0, hat], [3, 2, 0, 0, hat]);
PETS.push([0, 0, 1, 1, 0]);
const lines = [];
for (const [stage, mood, cracked, ready, hat] of PETS) {
  const pet = { stage: STAGES[stage], mood: MOODS[mood], ate: stage === 0 ? (cracked ? 40000 : 100) : 1000000, ready: !!ready,
    hat: hat ? { shape: SHAPES[hat - 1], color: 'blue' } : undefined };
  const h = [0, 1].map((idle) => hashOf(petLook(pet, { idle: !!idle }).pix));
  lines.push(`\t{${stage}, ${mood}, ${cracked}, ${ready}, ${hat}, {${h.map((v) => `0x${v.toString(16).padStart(8, '0')}u`).join(', ')}}},`);
}

console.log(`/* Generated by tools/pet_golden.mjs from pets.js: do not edit. */
/* stage, mood, cracked, ready, hat (1 + shape), hash of the cells with eyes open and idle */
static const struct { int stage, mood, cracked, ready, hat; uint32_t hash[2]; } pet_golden[] = {
${lines.join('\n')}
};`);
