// Prints the expected looks for test/host/test_pet.c from the web deck's
// pets.js, so the kit's pets (src/deck_pet.c) stay the same pixels:
//
//   node tools/pet_golden.mjs [path/to/pets.js] > test/host/pet_golden.h
//
// Each line is one look: its inputs and an FNV-1a hash of its cells
// ("x,y,key;" in rows, top to bottom, left to right).
import { pathToFileURL } from 'node:url';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(process.argv[2] || resolve(here, '../../../backend/internal/web/static/pets.js'));
const { petLook } = await import(pathToFileURL(src).href);

const STAGES = ['egg', 'baby', 'kid', 'grown', 'strong', 'mighty', 'legend'];
const MOODS = ['fed', 'hungry', 'weak', 'asleep'];
const SHAPES = ['hard hat', 'cap', 'beanie', 'helmet', 'wizard', 'beret', 'chef', 'crown', 'headphones',
  'propeller', 'top hat', 'cowboy', 'bandana'];
const COLORS = ['teal', 'blue', 'yellow', 'green', 'purple', 'pink', 'sky', 'ink'];

function fnv(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

function hashOf(pix) {
  const cells = [...pix].map(([k, ch]) => [...k.split(',').map(Number), ch]);
  cells.sort((a, b) => a[1] - b[1] || a[0] - b[0]);
  return fnv(cells.map(([x, y, ch]) => `${x},${y},${ch};`).join(''));
}

const cases = [];
const add = (stage, mood, cracked, idle, hat, color) => {
  const pet = { stage: STAGES[stage], mood: MOODS[mood], ate: stage === 0 ? (cracked ? 40000 : 100) : 1000000 };
  const opts = { idle: !!idle, hat: hat ? { shape: SHAPES[hat - 1], color: COLORS[color] } : undefined };
  const look = petLook(pet, opts);
  cases.push(`\t{${stage}, ${mood}, ${cracked}, ${idle}, ${hat}, ${color}, 0x${hashOf(look.pix).toString(16).padStart(8, '0')}u},`);
};

// Every stage, mood and idle, with a hat that changes from case to case.
let n = 0;
for (let stage = 0; stage < STAGES.length; stage++)
  for (let mood = 0; mood < MOODS.length; mood++)
    for (let idle = 0; idle < 2; idle++)
      for (const cracked of stage === 0 ? [0, 1] : [0]) {
        add(stage, mood, cracked, idle, 1 + (n % SHAPES.length), n % COLORS.length);
        n++;
      }
// Every hat on the three looks that wear one (kid, grown-up, weak grown-up), and none.
for (const [stage, mood] of [[2, 0], [3, 0], [3, 2]])
  for (let hat = 0; hat <= SHAPES.length; hat++) add(stage, mood, 0, 0, hat, hat % COLORS.length);

console.log(`/* Generated by tools/pet_golden.mjs from pets.js: do not edit. */
/* stage, mood, cracked, idle, hat (1 + shape), hat colour, hash of the cells */
static const struct { int stage, mood, cracked, idle, hat, color; uint32_t hash; } pet_golden[] = {
${cases.join('\n')}
};`);
